"""Generates a GISPlan from a natural-language prompt.

Provider-agnostic: the model call goes through :mod:`gis_assistant.llm`, which
defaults to Claude and can be switched to OpenAI with
``GIS_PLANNER_PROVIDER=openai``.
"""

from __future__ import annotations

import logging

from .llm import LLMProvider, build_provider
from .prompts import SYSTEM_PROMPT, build_user_prompt
from .schemas import GISPlan

logger = logging.getLogger("gis_assistant.planner")


class GISPlanner:
    """Generates GIS workflow plans using a provider's structured outputs."""

    def __init__(
        self, model: str | None = None, provider: LLMProvider | None = None
    ) -> None:
        """
        Args:
            model: Override the provider's default model.
            provider: Pre-built provider. Mainly for tests; when omitted the
                provider is chosen from the environment.
        """
        self._provider = provider or build_provider(model=model)

    @property
    def provider(self) -> LLMProvider:
        """The underlying provider, shared with other engine call sites."""
        return self._provider

    @property
    def model(self) -> str:
        return self._provider.model

    @property
    def provider_name(self) -> str:
        return self._provider.name

    def generate_plan(
        self,
        user_request: str,
        qgis_context: dict,
        answers: dict[str, str] | None = None,
    ) -> GISPlan:
        """Produce a structured GISPlan.

        Args:
            user_request: The natural-language GIS request.
            qgis_context: Current QGIS state (layers, project info, etc.).
            answers: Optional dict of {question_id: answer} from a previous
                     needs_clarification response.

        Returns:
            A validated GISPlan (may have status="needs_clarification").

        Raises:
            LLMError: The provider call failed or returned nothing usable.
        """
        user_prompt = build_user_prompt(user_request, qgis_context, answers)

        plan = self._provider.generate_structured(
            system=SYSTEM_PROMPT, user=user_prompt, schema=GISPlan
        )

        logger.info(
            "Plan generated by %s/%s: status=%s, %d steps, %d inputs",
            self._provider.name,
            self._provider.model,
            plan.status,
            len(plan.steps),
            len(plan.inputs),
        )
        return plan
